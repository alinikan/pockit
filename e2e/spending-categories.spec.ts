import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('search, staged category creation, optional descriptions, and bulk additions stay connected', async ({
  page,
}) => {
  await page.setViewportSize({ width: 402, height: 874 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Preview Pockit' }).click()
  const nav = page.locator('.bottom-nav')
  await nav.getByRole('button', { name: 'Activity', exact: true }).click()
  await page.getByRole('button', { name: 'Add transaction', exact: true }).click()
  const entry = page.getByRole('dialog', { name: 'New transaction' })
  await entry.getByRole('button', { name: /^Category Choose a category/ }).click()
  const search = entry.getByRole('searchbox', { name: 'Search category' })
  await search.fill('smokes')
  await entry.getByRole('button', { name: 'Use Cigarettes & Tobacco' }).click()
  await entry.getByRole('spinbutton', { name: 'Amount', exact: true }).fill('25')
  await entry.getByRole('button', { name: 'Save transaction' }).click()
  await expect(
    page.locator('.transaction-row').filter({ hasText: 'Cigarettes & Tobacco' }),
  ).toHaveCount(1)
  await nav.getByRole('button', { name: 'Budget', exact: true }).click()
  const allocation = page.locator('.allocation-row').filter({ hasText: 'Cigarettes & Tobacco' })
  await expect(allocation).toContainText('$25')
  await expect(allocation).toContainText('$0')
  await page.getByRole('button', { name: 'Browse categories', exact: true }).click()
  const library = page.getByRole('dialog', { name: 'Browse spending categories' })
  await library.getByRole('searchbox').fill('tobacco')
  await expect(library.getByRole('checkbox')).toHaveCount(0)
  await library.getByRole('searchbox').fill('lego')
  await library.getByRole('checkbox', { name: /Toys & Games/ }).check()
  await library.getByRole('searchbox').fill('pharmacy')
  await library.getByRole('checkbox', { name: /Medicines & Pharmacy/ }).check()
  await library.screenshot({ path: '/tmp/pockit-category-library.png' })
  const accessibility = await new AxeBuilder({ page }).include('.modal').analyze()
  expect(accessibility.violations).toEqual([])
  await library.getByRole('button', { name: 'Add 2 categories' }).click()
  await expect(page.locator('.allocation-row').filter({ hasText: 'Toys & Games' })).toHaveCount(1)
  await nav.getByRole('button', { name: 'Home', exact: true }).click()
  await page
    .getByRole('button', { name: 'View Cigarettes & Tobacco transactions', exact: true })
    .click()
  await expect(page.getByRole('dialog')).toContainText('$25.00')
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Preview Pockit' }).click()
  await nav.getByRole('button', { name: 'Activity', exact: true }).click()
  await page.getByRole('button', { name: 'Add transaction', exact: true }).click()
  await entry.getByRole('button', { name: /^Category Choose a category/ }).click()
  await search.fill('toys')
  await entry.getByRole('button', { name: 'Use Toys & Games' }).click()
  await entry.screenshot({ path: '/tmp/pockit-category-entry.png' })
  await expect(entry.getByText(/Added when you save/)).toHaveCount(0)
  const picker = await new AxeBuilder({ page }).include('.modal').analyze()
  expect(picker.violations).toEqual([])
})
